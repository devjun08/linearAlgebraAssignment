import numpy as np
import math

np.set_printoptions(suppress=True, precision=6)

# 각도를 라디안으로 변환
theta1 = math.radians(25)
theta2 = math.radians(15)

# 계수행렬 A
A = np.array([
    [math.cos(theta1), -math.cos(theta2)],
    [math.sin(theta1), math.sin(theta2)]
], dtype=float)

# 상수벡터 b
b = np.array([0, 30], dtype=float)

# 첫 번째 열 교체
A1 = A.copy()
A1[:, 0] = b

# 두 번째 열 교체
A2 = A.copy()
A2[:, 1] = b

print("계수행렬 A")
print(A)

print("A1: 첫 번째 열을 b로 교체")
print(A1)

print("A2: 두 번째 열을 b로 교체")
print(A2)

# 행렬식 계산
D = np.linalg.det(A)
D1 = np.linalg.det(A1)
D2 = np.linalg.det(A2)

print("D = det(A) =", round(D, 6))
print("D1 = det(A1) =", round(D1, 6))
print("D2 = det(A2) =", round(D2, 6))

# 크래머의 규칙
if np.isclose(D, 0):
    print("det(A)가 0이므로 유일한 해가 없습니다.")
else:
    T1 = D1 / D
    T2 = D2 / D

    print("크래머의 규칙 계산")
    print(f"T1 = {T1:.4f}")
    print(f"T2 = {T2:.4f}")

    # 검산
    equation1 = math.cos(theta1) * T1 - math.cos(theta2) * T2
    equation2 = math.sin(theta1) * T1 + math.sin(theta2) * T2

    print("검산")
    print(f"수평 방향 합 = {equation1:.6f}")
    print(f"수직 방향 합 = {equation2:.6f}")

