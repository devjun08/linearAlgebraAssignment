import numpy as np

np.set_printoptions(suppress=True, precision=2)

# 계수행렬 A
A = np.array([
    [1, -1, 1],
    [1, 1, -2],
    [1, 2, 1]
], dtype=float)

# 상수벡터 b
b = np.array([0, 1, 6], dtype=float)

print("계수행렬 A")
print(A)

print("상수벡터 b")
print(b)

# A의 행렬식
D = round(np.linalg.det(A))

print("D = det(A) =", D)

if D == 0:
    print("det(A)가 0이므로 크래머의 규칙을 적용할 수 없습니다.")
else:
    determinants = []
    solution = []

    for i in range(A.shape[1]):
        # A 복사
        Ai = A.copy()

        # i번째 열을 b로 교체
        Ai[:, i] = b

        # 행렬식 계산
        Di = round(np.linalg.det(Ai))
        determinants.append(Di)

        # 크래머의 규칙
        xi = Di / D
        solution.append(xi)

        print(f"A{i + 1}: {i + 1}번째 열을 b로 교체")
        print(Ai)

        print(f"D{i + 1} = det(A{i + 1}) = {Di}")
        print(f"x{i + 1} = {Di} / {D} = {xi}")
        print()

    solution = np.array(solution)

    print("최종 해")
    for i, value in enumerate(solution, start=1):
        print(f"x{i} = {value}")

    # 검산
    print("검산 결과 A @ x")
    print(A @ solution)

    print("원래 상수벡터 b")
    print(b)

