  print(A)
  print("\n행렬식 det(A)")
  print(det_A)
  print("\n여인수행렬 C")
  print(C)
  print("\n수반행렬 adj(A)")
  print(adj_A)
  print("\n역행렬 A^(-1)")
  print(inverse_A)
  print("\n검산 A x A^(-1)")
  print(np.round(A @ inverse_A, 10))

