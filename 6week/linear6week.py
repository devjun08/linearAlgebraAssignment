show_matrix("R3 <- R3 + 2R2", augmented)

# 3단계: 세 번째 피벗을 1로
augmented[2] = augmented[2] / augmented[2, 2]
show_matrix("R3의 피벗을 1로", augmented)

# 4단계: 세 번째 열의 위쪽 원소를 0으로
