def determinant_2x2(matrix):
  return (
      matrix[0][0] * matrix[1][1]
      - matrix[0][1] * matrix[1][0]
  )

# 계수 행렬 A
A = [
    [3, -2],
    [-5, 4]
]
# 상수벡터 b
b = [6, 0]

# A1: A의 첫 번째 열을 b로 교체
A1 = [
    [b[0], A[0][1]],
    [b[1], A[1][1]]
]
# A2: A의 두 번째 열을 b로 교체
A2 = [
    [A[0][0], b[0]],
    [A[1][0], b[1]]
]

# 각각의 행렬식 계산
D = determinant_2x2(A)
D1 = determinant_2x2(A1)
D2 = determinant_2x2(A2)

print("계수행렬 A =", A)
print("A1 =", A1)
print("A2 =", A2)
print("\ndet(A) =", D)
print("det(A1) =", D1)
print("det(A2) =", D2)

# 크래머의 규칙 적용
