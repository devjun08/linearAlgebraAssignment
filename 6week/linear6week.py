import numpy as np

# 세 벡터 정의
u1 = np.array([1, 1, 0], dtype=float)
u2 = np.array([1, 1, 1], dtype=float)
u3 = np.array([0, 2, 3], dtype=float)

# 세 벡터를 행으로 가지는 행렬 A
A = np.array([
    u1,
    u2,
    u3
])

print("벡터 행렬 A")
print(A)

# 행렬식 계산
det_A = np.linalg.det(A)

print("행렬식 det(A)")
print(round(det_A, 10))

# 평행육면체 부피 = |det(A)|
volume = abs(det_A)

print("평행육면체 S의 체적")
print(round(volume, 10))

# 스칼라 삼중 곱으로 검산
